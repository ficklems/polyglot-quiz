/**
 * Writes docs/CONTENT_REPORT.md from the content folder: what is in the dataset, what is
 * served in each language and why the rest is withheld. Run with `npm run content:report`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { LANGUAGES, SINGLE_ANSWER_TYPES, type Language } from '@pq/shared';
import { DEFAULT_CONTENT_DIR, loadContent } from './load-content';

const content = loadContent();
const { report, questions, categories } = content;
const n = (x: number) => x.toLocaleString('en-US');

const servedIn = (lang: Language) => questions.filter((q) => q.exclusions[lang].length === 0);
const audit = JSON.parse(
  readFileSync(join(DEFAULT_CONTENT_DIR, 'independent_audit_report.json'), 'utf8'),
) as { factStatusCumulative: Record<string, number> };

const lines: string[] = [];
lines.push('# Content report', '');
lines.push(
  '> Generated by `npm run content:report` from `content/`. Do not edit by hand.',
  `> Content version \`${content.version}\`.`,
  '',
);

lines.push('## Summary', '');
lines.push('| | Count |', '| --- | ---: |');
lines.push(`| Records read (dataset + legacy) | ${n(report.recordsRead)} |`);
lines.push(`| Invalid records (schema) | ${n(report.invalidRecords.length)} |`);
lines.push(`| Structural problems | ${n(report.structuralProblems.length)} |`);
lines.push(`| Repeated ids | ${n(report.duplicateIds.length)} |`);
lines.push(`| Exact duplicates found by the importer | ${n(report.exactDuplicates.length)} |`);
lines.push(
  `| Legacy questions (milestones 0–2) | ${report.legacyMerge.legacyRecords}, of which ${report.legacyMerge.retiredByMap} retired as duplicates |`,
);
lines.push(`| Categories | ${categories.length} |`);
for (const lang of LANGUAGES) {
  lines.push(`| Served in ${lang.toUpperCase()} | ${n(report.servableByLanguage[lang])} |`);
}
lines.push('', '**Every record is a draft.** Nothing is marked verified for publication.', '');

lines.push('## Fact verification (from the supplied audit)', '');
lines.push('| Status | Records |', '| --- | ---: |');
for (const [status, count] of Object.entries(audit.factStatusCumulative)) {
  lines.push(`| ${status.replaceAll('_', ' ')} | ${n(count)} |`);
}
lines.push('');

lines.push('## Why records are withheld', '');
lines.push('A record can have several reasons. Counts per language:', '');
lines.push(`| Reason | ${LANGUAGES.map((l) => l.toUpperCase()).join(' | ')} |`);
lines.push(`| --- | ${LANGUAGES.map(() => '---:').join(' | ')} |`);
const reasons = [...new Set(LANGUAGES.flatMap((l) => Object.keys(report.exclusionsByReason[l])))];
for (const reason of reasons) {
  const cells = LANGUAGES.map((l) =>
    n(
      report.exclusionsByReason[l][reason as keyof (typeof report.exclusionsByReason)[Language]] ??
        0,
    ),
  );
  lines.push(`| ${reason.replaceAll('_', ' ')} | ${cells.join(' | ')} |`);
}
lines.push('');

lines.push('## Playable questions per category', '');
lines.push(
  'Questions with one correct option (the formats rounds support today), served in each language. A category needs 10 to start a round.',
  '',
);
lines.push(`| Category | ${LANGUAGES.map((l) => l.toUpperCase()).join(' | ')} | All records |`);
lines.push(`| --- | ${LANGUAGES.map(() => '---:').join(' | ')} | ---: |`);
for (const c of categories) {
  const cells = LANGUAGES.map((lang) => {
    const count = servedIn(lang).filter(
      (q) => q.record.category === c.id && SINGLE_ANSWER_TYPES.includes(q.record.type),
    ).length;
    return count < 10 ? `**${count}** ⚠` : n(count);
  });
  const all = questions.filter((q) => q.record.category === c.id).length;
  lines.push(`| ${c.name.en} (\`${c.id}\`) | ${cells.join(' | ')} | ${n(all)} |`);
}
lines.push('');

lines.push('## Question formats', '');
lines.push(
  '| Format | All records | Served in EN | Playable today |',
  '| --- | ---: | ---: | --- |',
);
const types = [...new Set(questions.map((q) => q.record.type))];
for (const type of types) {
  const all = questions.filter((q) => q.record.type === type).length;
  const en = servedIn('en').filter((q) => q.record.type === type).length;
  lines.push(
    `| ${type} | ${n(all)} | ${n(en)} | ${SINGLE_ANSWER_TYPES.includes(type) ? 'yes' : 'no (needs its own UI)'} |`,
  );
}
lines.push('');

const out = resolve(DEFAULT_CONTENT_DIR, '..', 'docs', 'CONTENT_REPORT.md');
writeFileSync(out, `${lines.join('\n')}\n`);
process.stdout.write(`Wrote ${out}\n`);
